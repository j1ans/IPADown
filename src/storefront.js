// 置顶顺序：常用三个在前，其余按中文名排序。
const TOP = ['CN', 'US', 'JP'];

function countryToStorefront(country) {
  const cc = String(country || '').trim().toUpperCase();
  return STOREFRONTS[cc] || STOREFRONTS.US;
}

function countryName(cc) {
  const c = String(cc || '').toUpperCase();
  return ZH[c] ? `${ZH[c]} (${c})` : c;
}

// 返回有序列表 [{code, name}]，CN/US/JP 置顶，其余按中文名拼音近似排序。
function countryList() {
  const rest = Object.keys(STOREFRONTS)
    .filter((c) => !TOP.includes(c))
    .sort((a, b) => (ZH[a] || a).localeCompare(ZH[b] || b, 'zh-Hans-CN'));
  const ordered = [...TOP, ...rest];
  return ordered.map((c) => ({ code: c, name: countryName(c) }));
}

function knownCountries() {
  return countryList().map((x) => x.code);
}

